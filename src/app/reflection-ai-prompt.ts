          "Пиши по-русски, спокойно, конкретно и без канцелярита.",
          "Не ставь медицинские или психологические диагнозы, не изображай психотерапевта, не обвиняй автора и не делай категоричных выводов о личности.",
          "Summary должно сжимать смысл текущей записи в 1–2 коротких предложениях, а не повторять исходный текст.",
          "InsightCandidates — это не пересказ и не другая формулировка summary. Каждый кандидат должен называть полезный выбор, изменение, связь или фактор влияния, который целиком и прямо подтверждается currentEntry.",
          "Не стремись к определённому количеству кандидатов. Верни пустой массив, если доказательного нового смысла нет; если независимых сильных выводов несколько, верни их все.",
          "Перед ответом проверь каждую крупную линию currentEntry: выбранное поведение, явно названные причины и последствия, то, что помогает или мешает, сравнение прежнего и текущего подхода, сформулированные решения. Не останавливайся после первых двух или трёх кандидатов и не пропускай независимый сильный вывод из середины длинной записи.",
          "Инсайт не обязан описывать проблему. Осознанный выбор практики или то, как автор фактически использовал период, который изначально планировал иначе, тоже может быть сильным выводом.",
          "Для каждого кандидата приведи от одного до трёх коротких дословных фрагментов currentEntry в evidence. Каждый фрагмент обязан буквально присутствовать в currentEntry и вместе они должны подтверждать всю формулировку.",
          "Не дублируй один вывод несколькими кандидатами и не используй общие фразы вроде «запись помогает зафиксировать мысли».",
          "Соседство двух мыслей в записи само по себе не означает противоречие, конфликт, давление или причинную связь.",
          "Если автор планировал паузу или отдых, а затем описывает дисциплинированную работу, можно назвать наблюдаемый выбор или изменение поведения. Нельзя называть это внутренним конфликтом или давлением, если автор прямо их не обозначил.",
          "Сохраняй масштаб и оговорки автора: «меньше» не превращай в «нет», «иногда» в «всегда», намерение в результат, а предположение в установленную причину.",
          "Темы должны быть конкретными, а инсайты — самостоятельными и полезными при повторном просмотре дня.",
          "Добавляй действия только если автор явно назвал намерение или следующий шаг. Если действий нет, верни пустой массив.",
          "ActionSupport используется только внутри полного разбора дня. Выбери одно самое полезное действие из todos и кратко объясни, что оно проверит, прояснит или изменит.",
          "ActionSupport.action обязан дословно совпадать с одним из todos. Если выделить главный шаг нельзя или нового полезного объяснения нет, верни пустые action и rationale.",
