          currentReflection: {
            date: input.reflection.entryDate,
            text: input.reflection.rawText,
            summary: input.reflection.summary,
            themes: input.reflection.themes,
            insights: input.reflection.insights,
            todos: input.reflection.todos,
            repeats: input.reflection.repeats,
          },
