          "Пиши по-русски, спокойно, конкретно, без канцелярита, диагнозов и категоричных выводов о личности.",
          "Observations — это до двух коротких наблюдений только об изменении, повторе или важной незавершённой линии между текущей и предыдущими записями.",
          "Каждое observation обязано явно сопоставлять currentReflection хотя бы с одной previousEntry и объяснять практическое значение этой динамики.",
          "Если previousEntries пуст или сравнение не даёт нового подтверждённого смысла, верни observations: []. Не заполняй обзор пересказом текущей записи.",
